<?php
/**
 * Administrator-only front-end comparison for one chapter revision.
 *
 * Loaded by single.php when ?compare=1 is requested. Keeping the complete
 * comparison here leaves the normal chapter template concerned only with the
 * reading page.
 *
 * @package kungfu_2026
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$akw_post     = get_post();
$akw_revision = akw_get_previous_revision( $akw_post );

if ( ! $akw_post || ! $akw_revision || ! current_user_can( 'manage_options' ) ) {
	return;
}

$akw_title_diff   = akw_revision_text_diff( $akw_revision->post_title, $akw_post->post_title );
$akw_content_diff = akw_revision_text_diff(
	akw_revision_compare_text( $akw_revision->post_content ),
	akw_revision_compare_text( $akw_post->post_content )
);
$akw_change_view = akw_get_revision_change_view();

$akw_date_format = get_option( 'date_format' ) . ' ' . get_option( 'time_format' );
$akw_old_date    = mysql2date( $akw_date_format, $akw_revision->post_modified );
$akw_new_date    = mysql2date( $akw_date_format, $akw_post->post_modified );
?>
<article <?php post_class( 'revision-compare revision-compare--changes-' . $akw_change_view ); ?>>
	<header class="revision-compare__head">
		<a class="revision-compare__back" href="<?php echo esc_url( get_permalink( $akw_post ) ); ?>">&larr; <?php esc_html_e( 'Back to chapter', 'kungfu_2026' ); ?></a>
		<p class="revision-compare__eyebrow"><?php esc_html_e( 'Revision comparison', 'kungfu_2026' ); ?></p>
		<h1 class="revision-compare__title"><?php echo esc_html( get_the_title( $akw_post ) ); ?></h1>
		<p class="revision-compare__post-id">
			<?php
			printf(
				/* translators: %d: WordPress post ID. */
				esc_html__( 'Post ID: %d', 'kungfu_2026' ),
				(int) $akw_post->ID
			);
			?>
		</p>
		<p class="revision-compare__summary">
			<?php
			printf(
				/* translators: 1: previous revision date. 2: current version date. */
				esc_html__( 'Previous saved version from %1$s compared with the current version from %2$s.', 'kungfu_2026' ),
				esc_html( $akw_old_date ),
				esc_html( $akw_new_date )
			);
			?>
		</p>
	</header>

	<nav class="revision-compare__filters" aria-label="<?php esc_attr_e( 'Visible revision changes', 'kungfu_2026' ); ?>">
		<?php
		$akw_filters = array(
			'both'    => __( 'Both', 'kungfu_2026' ),
			'deleted' => __( 'Deleted', 'kungfu_2026' ),
			'added'   => __( 'New', 'kungfu_2026' ),
			'plain'   => __( 'Neither', 'kungfu_2026' ),
		);
		foreach ( $akw_filters as $akw_filter_value => $akw_filter_label ) :
			$akw_is_current = $akw_filter_value === $akw_change_view;
			?>
			<a
				class="revision-compare__filter revision-compare__filter--<?php echo esc_attr( $akw_filter_value ); ?><?php echo $akw_is_current ? ' is-current' : ''; ?>"
				href="<?php echo esc_url( akw_get_revision_change_url( $akw_filter_value, $akw_post ) ); ?>"
				<?php echo $akw_is_current ? 'aria-current="page"' : ''; // phpcs:ignore WordPress.Security.EscapeOutput -- Static attribute. ?>
			>
				<span class="revision-compare__filter-mark" aria-hidden="true"></span>
				<?php echo esc_html( $akw_filter_label ); ?>
			</a>
		<?php endforeach; ?>
	</nav>

	<section class="revision-compare__section" aria-labelledby="revision-title-heading">
		<h2 id="revision-title-heading"><?php esc_html_e( 'Title', 'kungfu_2026' ); ?></h2>
		<?php if ( $akw_title_diff ) : ?>
			<div class="revision-compare__diff"><?php echo $akw_title_diff; // phpcs:ignore WordPress.Security.EscapeOutput -- Generated by wp_text_diff(). ?></div>
		<?php else : ?>
			<p class="revision-compare__unchanged"><?php esc_html_e( 'The title did not change.', 'kungfu_2026' ); ?></p>
		<?php endif; ?>
	</section>

	<section class="revision-compare__section" aria-labelledby="revision-content-heading">
		<h2 id="revision-content-heading"><?php esc_html_e( 'Content', 'kungfu_2026' ); ?></h2>
		<?php if ( $akw_content_diff ) : ?>
			<div class="revision-compare__diff"><?php echo $akw_content_diff; // phpcs:ignore WordPress.Security.EscapeOutput -- Generated by wp_text_diff(). ?></div>
		<?php else : ?>
			<p class="revision-compare__unchanged"><?php esc_html_e( 'The content did not change.', 'kungfu_2026' ); ?></p>
		<?php endif; ?>
	</section>
</article>
